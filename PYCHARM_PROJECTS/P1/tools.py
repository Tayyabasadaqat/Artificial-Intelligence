def calculate_area_rectangle(l,b):
    print(f"Area of rectangle is: {l*b}")
def calculate_area_circle(r):
    print(f"Area of circle is:{2*3.142*r*r}")
def calculate_area_triangle(l,h):
    print(f"Area of triangle is: {0.5*l*h}")
