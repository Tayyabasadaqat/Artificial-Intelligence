def calculate_bonus(self,salary):
    self.bonus=self.salary*0.10
    print(f"Bonus is : {self.bonus}")
def calculate_allowance(self, salary):
    self.allowance=self.salary*0.15
    print(f"Allowance is : {self.allowance}")
def calculate_net_salary(self,bonus,allowance):
    self.net_salary=self.bonus+self.allowance
    print(f"Net salary is : {self.net_salary}")